// ── Replacement function ──

/**
 * Replace known emoji characters in a string with inline SVG icons.
 * Emoji inside HTML tag attributes are skipped to avoid breaking markup.
 */
export function replaceEmojiWithIcons(html: string): string {
  // Build a pattern that matches any of the emoji keys
  const emojiList = Object.keys(iconMap)
    .sort((a, b) => b.length - a.length) // longer first to match variation selectors
    .map((e) => escapeRegex(e))
    .join("|")

  const pattern = new RegExp(emojiList, "g")

  // Split the HTML into segments: tags and text content
  // We only replace emoji in text content, not inside tag attributes
  const segments = html.split(/(<[^>]*>)/)
  return segments
    .map((segment) => {
      // If it's an HTML tag, skip it
      if (segment.startsWith("<") && segment.endsWith(">")) {
        return segment
      }
      // Replace emoji in text content
      return segment.replace(pattern, (match) => iconMap[match]?.svg ?? match)
    })
    .join("")
}

// ── Utility ──

function escapeRegex(str: string): string {
  return str.replace(/[.*+?^${}()|[\]\\]/g, "\\$&")
}
